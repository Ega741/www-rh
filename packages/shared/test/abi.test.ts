const DESK = CREDIT_DESK_ABI as unknown as Abi;

function fn(abi: Abi, name: string): AbiFunction {
  const item = abi.find((i) => i.type === 'function' && i.name === name);
  expect(item, `function ${name}`).toBeDefined();
  return item as AbiFunction;
}
function ev(abi: Abi, name: string): AbiEvent {
  const item = abi.find((i) => i.type === 'event' && i.name === name);
  expect(item, `event ${name}`).toBeDefined();
  return item as AbiEvent;
}
function hasError(abi: Abi, name: string, inputs?: string[]): void {
  const item = abi.find((i) => i.type === 'error' && i.name === name);
  expect(item, `error ${name}`).toBeDefined();
  if (inputs && item && item.type === 'error') expect(item.inputs.map((i) => i.type)).toEqual(inputs);
}

describe('abi.generated.ts', () => {
  it('has the header sync-abi.mjs writes and four as-const exports', () => {
    const src = readFileSync(new URL('../src/abi.generated.ts', import.meta.url), 'utf8');
    expect(src.split('\n')[0]).toBe('// Generated by scripts/sync-abi.mjs from contracts/out — do not edit by hand.');
    for (const name of ['CREDIT_DESK_ABI', 'BEAGLE_TOKEN_ABI', 'MANUAL_PRICE_SOURCE_ABI', 'CHAINLINK_PRICE_SOURCE_ABI']) {
      expect(src).toContain(`\nexport const ${name} = [`);
    }
    expect((src.match(/ as const;\n/g) ?? []).length).toBe(4);
  });
});

describe('CreditDesk ABI (SPEC §3.4)', () => {
  it('has the exact event signatures', () => {
    const expected: Record<string, [string, boolean[]]> = {
      CreditPurchased: ['CreditPurchased(uint256,address,address,uint256,uint256,uint256)', [true, true, true, false, false, false]],
      BudgetOpened: ['BudgetOpened(uint256,address,address,uint128,uint64)', [true, true, true, false, false]],
      BudgetDrawn: ['BudgetDrawn(uint256,uint256,address,uint256,uint256,uint256,bytes32)', [true, true, true, false, false, false, false]],
      BudgetClosed: ['BudgetClosed(uint256,uint128)', [true, false]],
    };
    for (const [name, [signature, indexed]] of Object.entries(expected)) {
      const event = ev(DESK, name);
      expect(toEventSelector(event)).toBe(toEventSelector(signature));
      expect(event.inputs.map((i) => i.indexed === true)).toEqual(indexed);
    }
    expect(ev(DESK, 'CreditPurchased').inputs.map((i) => i.name)).toEqual([
      'receiptId',
      'workspace',
      'payer',
      'tokenAmount',
      'usdMicro',
      'priceE18',
    ]);
    expect(ev(DESK, 'BudgetDrawn').inputs.map((i) => i.name)).toEqual([
      'budgetId',
      'receiptId',
      'workspace',
      'tokenAmount',
      'usdMicro',
      'priceE18',
      'receiptHash',
    ]);
    for (const name of ['PriceSourceSet', 'MaxPriceAgeSet', 'MinBurnSet', 'OperatorSet', 'Paused', 'Unpaused', 'OwnershipTransferred']) ev(DESK, name);
  });

  it('has the function selectors the gateway and web use', () => {
    const selectors: Record<string, string> = {
      quote: 'quote(uint256)',
      burnForCredit: 'burnForCredit(address,uint256)',
      burnForCreditWithPermit: 'burnForCreditWithPermit(address,uint256,uint256,uint8,bytes32,bytes32)',
      openBudget: 'openBudget(address,uint128,uint64)',
      draw: 'draw(uint256,uint256,bytes32)',
      closeBudget: 'closeBudget(uint256)',
      budgetRemaining: 'budgetRemaining(uint256)',
      budgets: 'budgets(uint256)',
      setPriceSource: 'setPriceSource(address)',
      setMaxPriceAge: 'setMaxPriceAge(uint32)',
      setMinBurn: 'setMinBurn(uint256)',
      setOperator: 'setOperator(address)',
      recoverToken: 'recoverToken(address,address,uint256)',
    };
    for (const [name, signature] of Object.entries(selectors)) {
      expect(toFunctionSelector(fn(DESK, name)), name).toBe(toFunctionSelector(signature));
    }
    const views = ['token', 'tokenDecimals', 'nativeBurn', 'priceSource', 'maxPriceAge', 'minBurn', 'operator', 'totalBurned', 'totalUsdMicro', 'nextReceiptId', 'nextBudgetId', 'paused', 'owner', 'pendingOwner', 'DEAD', 'MAX_BUDGET_DURATION', 'quote', 'budgetRemaining', 'budgets'];
    for (const name of views) expect(fn(DESK, name).stateMutability, name).toBe('view');
    for (const name of ['burnForCredit', 'burnForCreditWithPermit', 'openBudget', 'draw', 'closeBudget', 'pause', 'unpause', 'acceptOwnership', 'transferOwnership']) {
      expect(fn(DESK, name).stateMutability, name).toBe('nonpayable');
    }
    expect(fn(DESK, 'quote').outputs.map((o) => o.name)).toEqual(['usdMicro', 'priceE18', 'updatedAt']);
    expect(fn(DESK, 'budgets').outputs.map((o) => `${o.name}:${o.type}`)).toEqual([
      'owner:address',
      'workspace:address',
      'cap:uint128',
      'drawn:uint128',
      'deadline:uint64',
      'closed:bool',
    ]);
    expect(fn(DESK, 'tokenDecimals').outputs[0]?.type).toBe('uint8');
    expect(fn(DESK, 'maxPriceAge').outputs[0]?.type).toBe('uint32');
  });

  it('has the constructor and custom errors', () => {
    const ctor = DESK.find((i) => i.type === 'constructor');
    expect(ctor?.type === 'constructor' && ctor.inputs.map((i) => i.type)).toEqual(['address', 'bool', 'address', 'address', 'address']);
    hasError(DESK, 'ZeroAddress', []);
    hasError(DESK, 'BadDecimals', []);
    hasError(DESK, 'BurnTooSmall', ['uint256', 'uint256']);
    hasError(DESK, 'QuoteTooSmall', []);
    hasError(DESK, 'PriceUnavailable', []);
    hasError(DESK, 'PriceStale', ['uint256', 'uint32']);
    hasError(DESK, 'NotOperator', []);
    hasError(DESK, 'BadBudgetParams', []);
    hasError(DESK, 'UnknownBudget', []);
    hasError(DESK, 'BudgetIsClosed', []);
    hasError(DESK, 'BudgetExpired', []);
    hasError(DESK, 'BudgetExceeded', ['uint256']);
    hasError(DESK, 'NotBudgetOwner', []);
    hasError(DESK, 'EnforcedPause', []);
  });

  it('encodes calls and decodes results/logs with viem', () => {
    const workspace = '0x0Bd7D308f8E1639FAb988df18A8011f41EAcAD73';
    const data = encodeFunctionData({ abi: CREDIT_DESK_ABI, functionName: 'burnForCredit', args: [workspace, 1000n * 10n ** 18n] });
    expect(data.slice(0, 10)).toBe(toFunctionSelector('burnForCredit(address,uint256)'));

    const encodedQuote = encodeFunctionResult({ abi: CREDIT_DESK_ABI, functionName: 'quote', result: [2_500_000n, 2_500_000_000_000_000n, 1_700_000_000n] });
    const quote: QuoteResult = decodeFunctionResult({ abi: CREDIT_DESK_ABI, functionName: 'quote', data: encodedQuote });
    expect(quote).toEqual([2_500_000n, 2_500_000_000_000_000n, 1_700_000_000n]);

    const event = getAbiItem({ abi: CREDIT_DESK_ABI, name: 'CreditPurchased' });
    const topics = encodeEventTopics({ abi: CREDIT_DESK_ABI, eventName: 'CreditPurchased', args: { receiptId: 7n, workspace, payer: workspace } });
    const logData = encodeAbiParameters(event.inputs.filter((i) => !i.indexed), [1000n * 10n ** 18n, 2_500_000n, 2_500_000_000_000_000n]);
    const decoded = decodeEventLog({ abi: CREDIT_DESK_ABI, eventName: 'CreditPurchased', topics: topics as [`0x${string}`, ...`0x${string}`[]], data: logData });
    const args: CreditPurchasedArgs = decoded.args;
    expect(args).toEqual({
      receiptId: 7n,
      workspace,
      payer: workspace,
      tokenAmount: 1000n * 10n ** 18n,
      usdMicro: 2_500_000n,
      priceE18: 2_500_000_000_000_000n,
    });
  });

  it('exposes the indexed event names and items', () => {
    expect(CREDIT_DESK_EVENT_NAMES).toEqual(['CreditPurchased', 'BudgetOpened', 'BudgetDrawn', 'BudgetClosed']);
    expect(CREDIT_DESK_EVENT_ITEMS.map((e) => e.name)).toEqual([...CREDIT_DESK_EVENT_NAMES]);
    expect(CREDIT_DESK_EVENTS.BudgetDrawn.type).toBe('event');
    expect(CREDIT_DESK_EVENTS.BudgetDrawn.inputs.map((i) => i.name)).toContain('receiptHash');
    expect(isCreditDeskEventName('BudgetOpened')).toBe(true);
    expect(isCreditDeskEventName('Paused')).toBe(false);
  });

  it('toBudgetStruct names the tuple', () => {
    const tuple: BudgetTuple = ['0x0Bd7D308f8E1639FAb988df18A8011f41EAcAD73', '0x000000000000000000000000000000000000dEaD', 500n, 20n, 1_700_000_000n, false];
    expect(toBudgetStruct(tuple)).toEqual({
      owner: '0x0Bd7D308f8E1639FAb988df18A8011f41EAcAD73',
      workspace: '0x000000000000000000000000000000000000dEaD',
      cap: 500n,
      drawn: 20n,
      deadline: 1_700_000_000n,
      closed: false,
    });
  });

  it('derives event arg types', () => {
    const opened: BudgetOpenedArgs = { budgetId: 1n, owner: '0x0Bd7D308f8E1639FAb988df18A8011f41EAcAD73', workspace: '0x0Bd7D308f8E1639FAb988df18A8011f41EAcAD73', cap: 1n, deadline: 2n };
    const drawn: BudgetDrawnArgs = { budgetId: 1n, receiptId: 2n, workspace: '0x0Bd7D308f8E1639FAb988df18A8011f41EAcAD73', tokenAmount: 3n, usdMicro: 4n, priceE18: 5n, receiptHash: `0x${'00'.repeat(32)}` };
    const closed: BudgetClosedArgs = { budgetId: 1n, drawn: 0n };
    const posted: PricePostedArgs = { priceE18: 1n, updatedAt: 2n, poster: '0x0Bd7D308f8E1639FAb988df18A8011f41EAcAD73' };
    expect(typeof opened.cap).toBe('bigint');
    expect(typeof drawn.receiptHash).toBe('string');
    expect(typeof closed.drawn).toBe('bigint');
    expect(typeof posted.poster).toBe('string');
  });
});

describe('ManualPriceSource ABI (SPEC §3.3)', () => {
  const abi = MANUAL_PRICE_SOURCE_ABI as unknown as Abi;
  it('has the price functions, events and errors', () => {
    // The implementation returns the pair unnamed: naming the outputs `priceE18`/`updatedAt` would
    // shadow the public storage getters of the same names (ABI output names are cosmetic for viem).
    expect(fn(abi, 'latestPrice').outputs.map((o) => o.type)).toEqual(['uint256', 'uint256']);
    expect(toFunctionSelector(fn(abi, 'post'))).toBe(toFunctionSelector('post(uint256)'));
    expect(toFunctionSelector(fn(abi, 'forcePrice'))).toBe(toFunctionSelector('forcePrice(uint256)'));
    expect(toFunctionSelector(fn(abi, 'setBounds'))).toBe(toFunctionSelector('setBounds(uint16,uint32)'));
    expect(toFunctionSelector(fn(abi, 'setPoster'))).toBe(toFunctionSelector('setPoster(address)'));
    for (const name of ['poster', 'priceE18', 'updatedAt', 'maxStepBps', 'minInterval', 'owner']) expect(fn(abi, name).stateMutability).toBe('view');
    expect(fn(abi, 'maxStepBps').outputs[0]?.type).toBe('uint16');
    expect(fn(abi, 'minInterval').outputs[0]?.type).toBe('uint32');
    expect(toEventSelector(ev(abi, 'PricePosted'))).toBe(toEventSelector('PricePosted(uint256,uint256,address)'));
    expect(toEventSelector(ev(abi, 'PriceForced'))).toBe(toEventSelector('PriceForced(uint256,uint256)'));
    ev(abi, 'PosterSet');
    ev(abi, 'BoundsSet');
    hasError(abi, 'NotPoster', []);
    hasError(abi, 'ZeroPrice', []);
    hasError(abi, 'PriceStepTooLarge', ['uint256', 'uint256']);
    hasError(abi, 'PostTooSoon', ['uint256']);
    hasError(abi, 'BadBounds', []);
  });
});

