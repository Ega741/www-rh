describe('BeagleToken and ERC20 ABIs', () => {
  it('BeagleToken has ERC-20 + permit + burn', () => {
    const abi = BEAGLE_TOKEN_ABI as unknown as Abi;
    for (const name of ['name', 'symbol', 'decimals', 'totalSupply', 'balanceOf', 'allowance', 'nonces', 'DOMAIN_SEPARATOR', 'TOTAL_SUPPLY']) {
      expect(fn(abi, name).stateMutability, name).toBe('view');
    }
    expect(toFunctionSelector(fn(abi, 'permit'))).toBe(toFunctionSelector('permit(address,address,uint256,uint256,uint8,bytes32,bytes32)'));
    expect(toFunctionSelector(fn(abi, 'burn'))).toBe(toFunctionSelector('burn(uint256)'));
    expect(toFunctionSelector(fn(abi, 'burnFrom'))).toBe(toFunctionSelector('burnFrom(address,uint256)'));
    expect(toFunctionSelector(fn(abi, 'approve'))).toBe(toFunctionSelector('approve(address,uint256)'));
    expect(toFunctionSelector(fn(abi, 'transferFrom'))).toBe(toFunctionSelector('transferFrom(address,address,uint256)'));
    expect(toEventSelector(ev(abi, 'Transfer'))).toBe(toEventSelector('Transfer(address,address,uint256)'));
    expect(toEventSelector(ev(abi, 'Approval'))).toBe(toEventSelector('Approval(address,address,uint256)'));
    hasError(abi, 'ERC2612ExpiredSignature', ['uint256']);
    hasError(abi, 'ERC20InsufficientBalance', ['address', 'uint256', 'uint256']);
  });

  it('ERC20_ABI is the minimal subset', () => {
    const abi = ERC20_ABI as unknown as Abi;
    const names = abi.filter((i) => i.type === 'function').map((i) => (i as AbiFunction).name).sort();
    expect(names).toEqual(['allowance', 'approve', 'balanceOf', 'decimals', 'name', 'symbol', 'totalSupply', 'transfer', 'transferFrom']);
    expect(toEventSelector(ev(abi, 'Transfer'))).toBe(toEventSelector('Transfer(address,address,uint256)'));
    expect(ev(abi, 'Approval').inputs.map((i) => i.indexed)).toEqual([true, true, false]);
    const data = encodeFunctionData({ abi: ERC20_ABI, functionName: 'approve', args: ['0x0Bd7D308f8E1639FAb988df18A8011f41EAcAD73', 5n] });
    expect(data.slice(0, 10)).toBe('0x095ea7b3');
  });
});
