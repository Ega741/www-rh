#!/usr/bin/env node
// Collects solana/deployments/<cluster>.json (cluster ∈ mainnet-beta | devnet | localnet) into
// packages/shared/src/deployments.generated.ts (docs/SPEC.md §3.1, §4.2). `--check` exits 1 when the committed
// file is stale. Files named *.local.json are ignored (gitignored per-machine overrides). Unknown JSON keys are
// ignored; every required key is validated (base58 32-byte keys, decimals 0–12, optional createdSlot ≥ 0).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'solana/deployments');
const target = resolve(root, 'packages/shared/src/deployments.generated.ts');
const check = process.argv.includes('--check');

/** Cluster order = the `Cluster` union in @beagle/shared/clusters. */
const CLUSTERS = ['mainnet-beta', 'devnet', 'localnet'];

const B58 = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
/** Decodes base58 (bitcoin alphabet); returns `null` for an invalid string. */
function base58Decode(s) {
  if (typeof s !== 'string' || s.length === 0) return null;
  let n = 0n;
  for (const c of s) {
    const i = B58.indexOf(c);
    if (i < 0) return null;
    n = n * 58n + BigInt(i);
  }
  const bytes = [];
  while (n > 0n) {
    bytes.push(Number(n % 256n));
    n /= 256n;
  }
  let leading = 0;
  for (const c of s) {
    if (c !== '1') break;
    leading++;
  }
  return Uint8Array.from([...new Array(leading).fill(0), ...bytes.reverse()]);
}
const isPubkey = (s) => base58Decode(s)?.length === 32;
const isUint = (n, max = Number.MAX_SAFE_INTEGER) => Number.isInteger(n) && n >= 0 && n <= max;

function validate(file, d) {
  const fail = (msg) => {
    throw new Error(`${file}: ${msg}`);
  };
  if (typeof d !== 'object' || d === null || Array.isArray(d)) fail('not a JSON object');
  const cluster = file.replace(/\.json$/, '');
  if (d.cluster !== cluster) fail(`cluster must be "${cluster}", got ${JSON.stringify(d.cluster)}`);
  for (const k of ['mint', 'tokenProgram', 'operator', 'memoProgram']) {
    if (!isPubkey(d[k])) fail(`${k} is not a base58 32-byte public key: ${JSON.stringify(d[k])}`);
  }
  if (!isUint(d.decimals, 12)) fail(`decimals must be an integer 0–12, got ${JSON.stringify(d.decimals)}`);
  if (typeof d.symbol !== 'string' || d.symbol.length === 0 || d.symbol.length > 16) fail('symbol must be a 1–16 character string');
  if (d.createdSlot !== undefined && !isUint(d.createdSlot)) fail(`createdSlot must be a non-negative integer, got ${JSON.stringify(d.createdSlot)}`);
  return {
    cluster,
    mint: d.mint,
    decimals: d.decimals,
    symbol: d.symbol,
    tokenProgram: d.tokenProgram,
    operator: d.operator,
    memoProgram: d.memoProgram,
    ...(d.createdSlot !== undefined ? { createdSlot: d.createdSlot } : {}),
  };
}

const entries = [];
for (const cluster of CLUSTERS) {
  const file = `${cluster}.json`;
  const path = resolve(dir, file);
  if (!existsSync(path)) continue;
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(path, 'utf8'));
  } catch (e) {
    throw new Error(`${file}: invalid JSON (${e instanceof Error ? e.message : String(e)})`);
  }
  entries.push(validate(file, parsed));
}

/** Single-quoted TS string literal. */
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
/** Object key: bare identifier when possible, quoted otherwise (`'mainnet-beta'`). */
const key = (s) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(s) ? s : q(s));

let body = '// Generated by scripts/sync-deployments.mjs from solana/deployments/*.json — do not edit by hand.\n';
body += "import type { Cluster } from './clusters.js';\n";
body += "import type { Deployment } from './addresses.js';\n\n";
body += 'export const DEPLOYMENTS: Readonly<Partial<Record<Cluster, Deployment>>> = {\n';
for (const d of entries) {
  body += `  ${key(d.cluster)}: {\n`;
  body += `    cluster: ${q(d.cluster)},\n`;
  body += `    mint: ${q(d.mint)},\n`;
  body += `    decimals: ${d.decimals},\n`;
  body += `    symbol: ${q(d.symbol)},\n`;
  body += `    tokenProgram: ${q(d.tokenProgram)},\n`;
  body += `    operator: ${q(d.operator)},\n`;
  body += `    memoProgram: ${q(d.memoProgram)},\n`;
  if (d.createdSlot !== undefined) body += `    createdSlot: ${d.createdSlot},\n`;
  body += '  },\n';
}
body += '};\n';

const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
if (check) {
  if (current !== body) {
    console.error('sync-deployments: packages/shared/src/deployments.generated.ts is stale. Run `pnpm deployments:sync`.');
    process.exit(1);
  }
  console.log(`sync-deployments: up to date (${entries.length} cluster(s))`);
} else {
  writeFileSync(target, body);
  console.log(`sync-deployments: wrote ${target} (${entries.map((d) => d.cluster).join(', ') || 'no clusters'})`);
}
