#!/usr/bin/env node
// Collects contracts/deployments/<chainId>.json into packages/shared/src/deployments.generated.ts.
// `--check` exits 1 when the committed file is stale.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'contracts/deployments');
const target = resolve(root, 'packages/shared/src/deployments.generated.ts');
const check = process.argv.includes('--check');

const REQUIRED = ['chainId', 'token', 'tokenSymbol', 'tokenDecimals', 'nativeBurn', 'creditDesk', 'priceSource',
  'priceSourceKind', 'deployBlock', 'owner', 'operator', 'poster'];
const ADDR = /^0x[0-9a-fA-F]{40}$/;

const entries = [];
if (existsSync(dir)) {
  for (const f of readdirSync(dir).filter((f) => /^\d+\.json$/.test(f)).sort((a, b) => Number(a.split('.')[0]) - Number(b.split('.')[0]))) {
    const d = JSON.parse(readFileSync(resolve(dir, f), 'utf8'));
    for (const k of REQUIRED) if (!(k in d)) throw new Error(`${f}: missing key ${k}`);
    for (const k of ['token', 'creditDesk', 'priceSource', 'owner', 'operator', 'poster']) {
      if (!ADDR.test(d[k])) throw new Error(`${f}: ${k} is not an address: ${d[k]}`);
    }
    if (Number(f.split('.')[0]) !== Number(d.chainId)) throw new Error(`${f}: chainId mismatch`);
    entries.push(d);
  }
}

let body = '// Generated by scripts/sync-deployments.mjs from contracts/deployments/*.json — do not edit by hand.\n';
body += "import type { Deployment } from './addresses.js';\n\n";
body += 'export const DEPLOYMENTS: Readonly<Record<number, Deployment>> = {\n';
for (const d of entries) {
  body += `  ${Number(d.chainId)}: {\n`;
  body += `    chainId: ${Number(d.chainId)},\n`;
  body += `    token: '${d.token}',\n`;
  body += `    tokenSymbol: ${JSON.stringify(String(d.tokenSymbol))},\n`;
  body += `    tokenDecimals: ${Number(d.tokenDecimals)},\n`;
  body += `    nativeBurn: ${Boolean(d.nativeBurn)},\n`;
  body += `    creditDesk: '${d.creditDesk}',\n`;
  body += `    priceSource: '${d.priceSource}',\n`;
  body += `    priceSourceKind: ${JSON.stringify(String(d.priceSourceKind))},\n`;
  body += `    deployBlock: ${Number(d.deployBlock)},\n`;
  body += `    owner: '${d.owner}',\n`;
  body += `    operator: '${d.operator}',\n`;
  body += `    poster: '${d.poster}',\n`;
  body += '  },\n';
}
body += '};\n';

const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
if (check) {
  if (current !== body) {
    console.error('sync-deployments: deployments.generated.ts is stale. Run `pnpm deployments:sync`.');
    process.exit(1);
  }
  console.log('sync-deployments: up to date');
} else {
  writeFileSync(target, body);
  console.log(`sync-deployments: wrote ${target} (${entries.length} chain(s))`);
}
