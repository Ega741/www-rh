#!/usr/bin/env node
// Copies the ABIs of the Beagle contracts from the Foundry build output into
// packages/shared/src/abi.generated.ts. `--check` exits 1 when the committed file is stale.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(root, 'contracts/out');
const target = resolve(root, 'packages/shared/src/abi.generated.ts');
const check = process.argv.includes('--check');

const CONTRACTS = [
  ['CREDIT_DESK_ABI', 'CreditDesk.sol/CreditDesk.json'],
  ['BEAGLE_TOKEN_ABI', 'BeagleToken.sol/BeagleToken.json'],
  ['MANUAL_PRICE_SOURCE_ABI', 'ManualPriceSource.sol/ManualPriceSource.json'],
  ['CHAINLINK_PRICE_SOURCE_ABI', 'ChainlinkPriceSource.sol/ChainlinkPriceSource.json'],
];

let body = '// Generated by scripts/sync-abi.mjs from contracts/out — do not edit by hand.\n';
for (const [name, file] of CONTRACTS) {
  const path = resolve(outDir, file);
  if (!existsSync(path)) {
    console.error(`sync-abi: missing ${path}. Run \`forge build\` in contracts/ first.`);
    process.exit(2);
  }
  const { abi } = JSON.parse(readFileSync(path, 'utf8'));
  body += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}

const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
if (check) {
  if (current !== body) {
    console.error('sync-abi: packages/shared/src/abi.generated.ts is stale. Run `pnpm abi:sync`.');
    process.exit(1);
  }
  console.log('sync-abi: up to date');
} else {
  writeFileSync(target, body);
  console.log(`sync-abi: wrote ${target}`);
}
